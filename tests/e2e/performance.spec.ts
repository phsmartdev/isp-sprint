import { expect, test, type Page } from '@playwright/test';

const SHOTS = process.env.E2E_SHOTS;
async function login(page: Page, email: string) {
  await page.goto('/login');
  await page.getByLabel('E-mail').fill(email);
  await page.getByLabel('Senha', { exact: true }).fill('Sprint@2026');
  await page.getByRole('button', { name: 'Entrar' }).click();
  await expect(page.getByRole('button', { name: /^Conta de / })).toBeVisible();
}
const shot = async (page: Page, name: string) => { if (SHOTS) await page.screenshot({ path: `${SHOTS}/${name}.png`, fullPage: true }); };

test('Gestão de desempenho: eventos de negócio, regras de atribuição versionadas e exploração com validação', async ({ page }) => {
  test.setTimeout(90_000);
  await page.setViewportSize({ width: 1440, height: 900 });
  await login(page, 'carlos@yepnet.test');
  await page.goto('/settings/desempenho');
  await expect(page.getByRole('heading', { name: 'Eventos e regras de atribuição' })).toBeVisible();
  await page.getByRole('button', { name: 'Reprocessar histórico' }).click();
  await expect(page.getByText(/Reprocessado:/)).toBeVisible();
  await expect(page.getByText('Oportunidade criada', { exact: true })).toBeVisible();
  await expect(page.getByText('Cliente reativado')).toBeVisible();
  await page.getByLabel('Parte do responsável em Negociação ganha').fill('80');
  await page.getByLabel('O que mudou').fill('Pré-venda divide 20% das vendas ganhas');
  await page.getByRole('button', { name: 'Salvar nova versão' }).click();
  await expect(page.getByText(/Versão \d+ em vigor/)).toBeVisible();
  await shot(page, 'perf-eventos');
  await page.getByRole('tab', { name: 'Explorar eventos' }).click();
  await page.getByLabel('Evento').selectOption({ label: 'Oportunidade criada' });
  await page.getByRole('button', { name: 'Oportunidade criada' }).first().click();
  const dr = page.getByRole('dialog', { name: 'Evento de negócio' });
  await expect(dr.getByText('Créditos')).toBeVisible();
  await expect(dr.getByRole('link', { name: 'Abrir registro de origem' })).toBeVisible();
  await shot(page, 'perf-explorar');
});

test('Indicadores, semáforo, scorecard e metas em cascata', async ({ page }) => {
  test.setTimeout(120_000);
  await page.setViewportSize({ width: 1440, height: 900 });
  await login(page, 'carlos@yepnet.test');
  await page.goto('/settings/desempenho?t=indicadores');
  await expect(page.getByRole('heading', { name: 'Semáforo' })).toBeVisible();
  await page.getByRole('button', { name: 'Criar todas' }).click();
  await expect(page.getByText(/indicador\(es\) criado/)).toBeVisible();
  await page.getByRole('listitem').filter({ hasText: 'Taxa de conversão' }).getByRole('button', { name: 'Editar' }).click();
  const ed = page.getByRole('dialog', { name: 'Editar indicador' });
  await expect(ed.getByText('Fórmula válida.')).toBeVisible();
  await ed.getByLabel('Fórmula').fill('ganhas / (ganhas + perdidas * 100');
  await expect(ed.getByText(/esperava/).first()).toBeVisible();
  await ed.getByLabel('Fórmula').fill('ganhas / (ganhas + perdidas) * 100');
  await ed.getByRole('button', { name: 'Testar no período atual' }).click();
  await expect(ed.getByText(/Resultado:/)).toBeVisible();
  await shot(page, 'perf-indicador');
  await ed.getByRole('button', { name: 'Cancelar' }).click();
  await page.getByRole('tab', { name: 'Scorecards' }).click();
  await page.getByRole('button', { name: 'Novo scorecard' }).click();
  const sc = page.getByRole('dialog', { name: 'Novo scorecard' });
  await sc.getByLabel('Nome da função').fill('Vendedor');
  await sc.getByLabel('Vendedor', { exact: true }).check();
  await sc.getByRole('button', { name: 'Adicionar indicador' }).click();
  await sc.getByRole('button', { name: 'Adicionar indicador' }).click();
  await sc.getByLabel('Peso 1').fill('30');
  await expect(sc.getByText('75%')).toBeVisible();
  await sc.getByRole('button', { name: 'Salvar' }).click();
  await expect(page.getByText('Scorecard salvo')).toBeVisible();
  await shot(page, 'perf-scorecards');

  await page.goto('/desempenho/metas');
  await page.getByRole('button', { name: 'Nova meta' }).click();
  const ng = page.getByRole('dialog', { name: 'Nova meta' });
  await ng.getByLabel('Título').fill('Vendas da empresa no mês');
  await ng.getByLabel('Indicador').selectOption({ label: 'Vendas ganhas' });
  await ng.getByLabel('Valor-alvo').fill('30');
  await ng.getByLabel('Como as metas desdobradas desta consolidam').selectOption('soma');
  await ng.getByRole('button', { name: 'Criar meta' }).click();
  await expect(page.getByRole('button', { name: /Vendas da empresa no mês/ })).toBeVisible();
  await page.getByRole('button', { name: 'Desdobrar' }).first().click();
  const dd = page.getByRole('dialog', { name: /Desdobrar/ });
  await dd.getByLabel('Título').fill('Vendas do Residencial');
  await dd.getByLabel('Nível').selectOption('equipe');
  await dd.getByLabel('Equipe').selectOption({ label: 'Residencial' });
  await dd.getByLabel('Valor-alvo').fill('18');
  await dd.getByRole('button', { name: 'Criar meta' }).click();
  await expect(page.getByRole('button', { name: /Vendas do Residencial/ })).toBeVisible();
  await page.getByRole('button', { name: /Vendas da empresa no mês/ }).click();
  const gd = page.getByRole('dialog', { name: 'Meta' });
  await expect(gd.getByText('Desdobramento')).toBeVisible();
  await gd.getByLabel('Novo alvo').fill('35');
  await gd.getByLabel('Motivo').fill('Campanha de fim de ano antecipada');
  await gd.getByRole('button', { name: 'Salvar revisão' }).click();
  await expect(gd.getByText(/original/)).toBeVisible();
  await shot(page, 'perf-meta');
  await gd.getByRole('button', { name: 'Fechar' }).click();
  await page.getByRole('tab', { name: 'Objetivos' }).click();
  await page.getByRole('button', { name: 'Novo objetivo' }).click();
  const ob = page.getByRole('dialog', { name: 'Novo objetivo' });
  await ob.locator('#ob-t').fill('Aumentar a receita comercial');
  await ob.getByLabel('Nível').selectOption('estrategico');
  await ob.getByRole('button', { name: 'Criar' }).click();
  await expect(page.getByRole('heading', { name: 'Aumentar a receita comercial' })).toBeVisible();
  await shot(page, 'perf-objetivos');
});
